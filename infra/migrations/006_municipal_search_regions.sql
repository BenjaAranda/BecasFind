INSERT INTO becas_regiones (id_beca, id_region)
SELECT b.id_beca, r.id_region
FROM municipios m
JOIN instituciones i ON i.nombre = m.institucion
JOIN becas b ON b.id_institucion = i.id_institucion
JOIN regiones r ON r.abreviatura = m.region
WHERE NOT EXISTS (SELECT 1 FROM becas_regiones br WHERE br.id_beca = b.id_beca)
ON CONFLICT DO NOTHING;

